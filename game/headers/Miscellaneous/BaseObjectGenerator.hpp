#ifndef BASE_OBJECT_GENERATOR_HPP
#define BASE_OBJECT_GENERATOR_HPP

#include "Data/ObjectDataEnums.hpp"

/**
 * @file BaseObjectGenerator
 * @brief This file contains BaseObjectGenerator class, which is used in another ObjectGenerator classes.
 * Objects of this class are used in WorldManager, in order to generate various objects on the world map.
 *
 * In this class, updateObjects() is used to generate objects, in number which should meet the desired number of objects, and/or
 * make each object do some logic related to its behaviour.
 *
 * This class contains mostly basic setters and getters for the class. More advanced methods used for object generation are in ObjectGenerator class.
 */
class BaseObjectGenerator{

private:
    unsigned int object_quantity_;
    const ObjectType object_type_;

public:
    /**
     * @brief Construct a new BaseObjectGenerator object.
     *
     * @param init_object_quantity The initial number of objects to generate onto world map.
     * @param object_type The type of objects to be generated by this generator.
     */
    explicit BaseObjectGenerator(const int init_object_quantity, const ObjectType object_type):
        object_quantity_(init_object_quantity),object_type_(object_type){}

    /**
     * @brief Create and/or do some logic related to objects generated by this object.
     *
     * This method is used to generate objects into world map, in number which should meet the desired number of objects,
     * and/or make each object do some logic related to its behaviour.
     *
     * When creating new objects into world map, old objects by default are not destroyed. Instead, new objects are
     * created in addition to old ones.
     *
     */
    virtual void updateObjects()=0;

    /**
     * @brief Get the number of objects, which this generator is creating, and which is number of these objects in world map.
     *
     */
    int getObjectQuantity() const{
        return object_quantity_;
    }

    /**
     * @brief Set the number of objects, which this generator is creating.
     * Also, call updateObjects() in order to update world map new objects.
     * If new number of objects is smaller than previous one, some objects will be destroyed in order to matach the values.
     */
    void setObjectQuantity(const unsigned int new_value){
        object_quantity_ = new_value;
        updateObjects();
    }

    /// @brief Get ObjectType of objects generated by this generator.
    ObjectType getObjectType() const{
        return object_type_;
    }

    BaseObjectGenerator(const BaseObjectGenerator&) = delete;
    BaseObjectGenerator& operator=(const BaseObjectGenerator&) = delete;

    };

#endif