/**
 * @class MinesGenerator
 * @brief Object generator for generating objects of Mine class into world map.
 */
class MinesGenerator: public ObjectGenerator<Mine>{
private:
    std::vector<std::shared_ptr<Mine>> objects_;

public:
    /**
     * @brief Construct a new MinesGenerator object.
     *
     * @param init_object_quantity The initial number of objects to generate onto world map.
     */
    explicit MinesGenerator(const int init_object_quantity):ObjectGenerator(init_object_quantity, constants::MINES_OBJECT_TYPE){
        updateObjects();
    };

    void updateObjects() override{
        if (objects_.size() != static_cast<size_t>(getObjectQuantity())){
            const int n_objects_on_map = WorldManager::getInstance().getWorldMap().countNumberOfObjectOfType(getObjectType());

            if(n_objects_on_map > getObjectQuantity()){
                int n_objects_to_remove = n_objects_on_map - getObjectQuantity();
                for(const auto& object: getWorldObjectsOnMap()){
                    if(object.get().getInteractiveObjectType() == getObjectType()){
                        int x_pos = object.get().getXPos();
                        int y_pos = object.get().getYPos();
                        WorldManager::getInstance().getWorldMap().getTileAt(x_pos, y_pos).removeObjectOnTile();

                        --n_objects_to_remove;
                        if(n_objects_to_remove == 0){
                            objects_.erase(std::remove_if(objects_.begin(), objects_.end(),
                                [&object](const std::shared_ptr<Mine>& mine) {
                                    return mine.get() == &object.get();
                                }), objects_.end());
                            break;
                        }
                    }
                }
                return;
            }

            const size_t n_object_to_generate = std::max(getObjectQuantity()-n_objects_on_map, 0);
            auto possible_tiles = getValidTilesForObjectGenerator();
            auto used_tiles = chooseNFromContainer(possible_tiles, n_object_to_generate);
            if(possible_tiles.size() < n_object_to_generate){
                throw MapStructureError("Not enough tiles to generate new objects");
            }

            for (auto& tile: used_tiles){

                std::shared_ptr<Mine> new_object = std::make_shared<Mine>();
                int x_pos = tile.get().getXPos();
                int y_pos = tile.get().getYPos();
                new_object->setPos({x_pos, y_pos});
                tile.get().addObjectOnTile(new_object);
                objects_.push_back(new_object);

            }
        }
        else{
            for(const std::shared_ptr<Mine>& mine: objects_){
                int player_id = mine->getPlayerID();
                if (player_id != -1 && !PlayerManager::getInstance().isPlayerActive(player_id)){
                    mine->setPlayerID(-1);
                }
            }
        }

    }

    std::vector<std::reference_wrapper<Mine>> getWorldObjectsOnMap() override{
        std::vector<std::reference_wrapper<Mine>> mines;

        for(const std::shared_ptr<Mine>& mine: objects_){
            mines.push_back(*mine);
        }
        return mines;
    }

    /// @brief Make all Mines, which belonged to player with given ID, neutral, by setting their owner ID to -1.
    void removeMineOwnershipOfPlayer(const int player_id){
        for(const auto& mine: objects_){
            if(mine->getPlayerID() == player_id){
                mine->setPlayerID(-1);
            }
        }
    }

    /// @brief Make all Mines call addResourceToPlayer(), which will be Resources associated with mines to players, who control those mines.
    void addResourcesToPlayers(){
        for(const auto& mine: objects_){
            mine->addResourceToPlayer();
        }
    }

};
