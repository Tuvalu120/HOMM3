template<typename T>
/**
 * @class ObjectGenerator
 * @brief ObjectGenerator is a template class responsible for placing, updating, and managing
 * interactive objects on the world map, ensuring correct quantities and valid placement.
 *
 * @tparam T The type of interactive object to generate. Must inherit from WorldGeneratedInteractiveObject.
 */
class ObjectGenerator: public BaseObjectGenerator{

protected:

    /**
     * @brief Get a list of valid tiles on which object can be placed.
     *
     * This function iterates over all tiles in the world map and selects those that are valid,
     * by checking if they are empty, walkable, and there are no other object in neighbourhood of tile.
     * The function returns a vector of references to the valid WorldTile objects.
     *
     * @return std::vector<std::reference_wrapper<WorldTile>> A vector containing references to valid tiles for generating objects.
     */
    const std::vector<std::reference_wrapper<WorldTile>> getValidTilesForObjectGenerator() const{
        std::vector<std::reference_wrapper<WorldTile>> valid_tiles;
        bool flag_are_neighbours_valid;
        for (const auto& tile : WorldManager::getInstance().getWorldMap().getTileMap()){
            if (tile->isTileWalkable()){
                flag_are_neighbours_valid = true;
                for(const WorldTile& neighbour_tile: WorldManager::getInstance().getWorldMap().getNeighboursOfTile(tile->getXPos(), tile->getYPos()).first){
                    if (neighbour_tile.hasInteractiveObject()){
                        flag_are_neighbours_valid = false;
                        break;
                    }
                }
                if (flag_are_neighbours_valid){
                    valid_tiles.push_back(*tile);
                }
            }
        }
        return valid_tiles;
    }

public:
    static_assert(std::is_base_of<WorldGeneratedInteractiveObject, T>::value, "T must inherit from WorldGeneratedInteractiveObject");

    /**
     * @brief Construct a new Object Generator object
     *
     * @param init_object_quantity The initial number of objects to generate onto world map.
     * @param object_type The type of objects to be generated by this generator.
     */
    explicit ObjectGenerator(const int init_object_quantity, const ObjectType object_type):
        BaseObjectGenerator(init_object_quantity, object_type){};

    void updateObjects() override{
        const int n_objects_on_map = WorldManager::getInstance().getWorldMap().countNumberOfObjectOfType(getObjectType());

        if(n_objects_on_map > getObjectQuantity()){
            int n_objects_to_remove = n_objects_on_map - getObjectQuantity();
            for(const auto& object: getWorldObjectsOnMap()){
                if(object.get().getInteractiveObjectType() == getObjectType()){
                    int x_pos = object.get().getXPos();
                    int y_pos = object.get().getYPos();
                    WorldManager::getInstance().getWorldMap().getTileAt(x_pos, y_pos).removeObjectOnTile();
                    --n_objects_to_remove;
                    if(n_objects_to_remove == 0){
                        break;
                    }
                }
            }
            return;
        }

        const size_t n_object_to_generate = std::max(getObjectQuantity()-n_objects_on_map, 0);
        auto possible_tiles = getValidTilesForObjectGenerator();
        if(possible_tiles.size() < n_object_to_generate){
            throw MapStructureError("There is not enough tiles to generate new objects on the map");
            }
        auto used_tiles = chooseNFromContainer(possible_tiles, n_object_to_generate);


        for (auto& tile: used_tiles){

            std::shared_ptr<T> new_object = std::make_shared<T>();
            int x_pos = tile.get().getXPos();
            int y_pos = tile.get().getYPos();
            new_object->setPos({x_pos, y_pos});
            tile.get().addObjectOnTile(new_object);

        }
    }

    /// @brief Get vector of all objects, which were generated by this object generator, based on ObjectType of objects on world map.
    virtual std::vector<std::reference_wrapper<T>> getWorldObjectsOnMap(){
        std::vector<std::reference_wrapper<T>> objects;
        for(const auto& tile: WorldManager::getInstance().getWorldMap().getTileMap()){
            if(tile->hasInteractiveObject() && tile->getObjectOnTile().getInteractiveObjectType() == getObjectType()){
                objects.push_back(static_cast<T&>(tile->getObjectOnTile()));
            }
        }
        return objects;
    }

};
