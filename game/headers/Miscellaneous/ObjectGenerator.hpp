/**
 * @class WorldNeutralTroopsGenerator
 * @brief Object generator for generating objects of WorldNeutralTroop class into world map.
 */
class WorldNeutralTroopsGenerator : public ObjectGenerator<WorldNeutralTroops>{
private:

    /// @brief Call setUpArmy() of all objects generated by this object, which creates Army objects associated with each of WorldNeutralTroop objects on world map.
    void setUpNeutralTroops(){
        for(const auto& object: getWorldObjectsOnMap()){
            object.get().setUpArmy(WorldManager::getInstance().getGameProgressValue());
        }
    }

public:
    /**
     * @brief Construct a new WorldNeutralTroopsGenerator object.
     *
     * @param init_object_quantity The initial number of objects to generate onto world map.
     */
    explicit WorldNeutralTroopsGenerator(const int init_object_quantity):ObjectGenerator(init_object_quantity, constants::NEUTRAL_TROOPS_OBJECT_TYPE){};

    void updateObjects() override{
        ObjectGenerator::updateObjects();
        setUpNeutralTroops();
    }

};
