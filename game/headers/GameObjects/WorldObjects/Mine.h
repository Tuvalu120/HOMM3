/**
 * @file Mine.h
 * @author Bartosz Han
 * @brief This file contains Mine class, which is one of WorldGeneratedInteractiveObjects.
 * Players can capture mines, in order to get additional resources.
 *
 */
#ifndef MINE_H
#define MINE_H

#include "GameObjects/BaseObjects/WorldGeneratedInteractiveObject.h"
#include "GameObjects/BaseObjects/OwnedByPlayer.h"
#include "GameObjects/Army.h"
#include "Miscellaneous/IPainter.h"

/**
 * @class Mine
 * @brief This class is one of WorldGeneratedInteractiveObjects. Players can capture mines, in order to get additional resources.
 *
 * When player interacts with neutral or mine belonging to  enemy, a battle is occurring.
 * If player wins battle with mine's army, it gets ownership of this mine.
 *
 * Mines generate for player owning them resources every day.
 *
 */
class Mine: public WorldGeneratedInteractiveObject, public OwnedByPlayer{

    private:

    Resource resource_;
    int quantity_;
    std::shared_ptr<Army> mine_army_;

    /// @brief Generate new army for the mine to own. Power of army is based of value of game progress.
    void resetArmy();


    public:
    Mine();
    void interact() override;
    void setPlayerID(const int new_player_id) override;

    /// @brief Get Resource type, which mine is generating for players.
    Resource getResourceType() const;

    /// @brief Get number indicating quantity of resources this mine provides each time it gives player resources.
    int getResourceQuantity() const;

    /// @brief Give player, who is owning the mine, resource generated by this mine at provided quantity.
    /// If this mine does not belong to any player, this method does not have any effect.
    void addResourceToPlayer();
    void drawAdditionalData(IPainter& painter) const override;

    /// @brief Get reference of army, which is used for defense of mine during world army's attack.
    /// This method can be used even when no battle with this is happening right now.
    Army& getMineArmy() const;

    /// @brief Check, is two mines are at same position and generate same resource at same quantity.
    bool operator==(const Mine& other) const;

};

#endif