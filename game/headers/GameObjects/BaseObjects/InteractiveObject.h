/**
 * @file InteractiveObject.h
 * @author Bartosz Han
 * @brief This file contains InteractiveObject class, which is used to create objects, which can be interacted with other objects,
 * such as stacks or armies.
 *
 */
#ifndef INTERACTIVE_OBJECT_H
#define INTERACTIVE_OBJECT_H

#include "GameObjects/BaseObjects/DrawableObject.h"
#include "Data/ObjectDataEnums.hpp"
#include "Data/Constants.hpp"
#include "Miscellaneous/IPainter.h"

class WorldArmy;
class Player;
class QPixmap;

/**
 * @class InteractiveObject
 * @brief This abstract class is used by objects, which can be interacted by other objects, such as stacks or armies.
 * when another object controlled by is close enough this object, this object should call its interact() method to do logic
 * related to this object.
 * This class is laso responsible for controlling the state of the object, and informing other components of the, if this object should
 * be removed from the game.
 * Objects of this class can be placed into tiles of tile maps and this class contains information about position of the object.
 *
 */
class InteractiveObject: public DrawableObject{

protected:
    const ObjectType interactive_object_type_;
    int priority_;
    int x_pos_;
    int y_pos_;
    bool destroy_after_interaction_;

public:
    /**
     * @brief Construct a new Interactive Object object.
     *
     * @param initial_texture_name Path to texture of this object.
     * @param object_type Type of the object.
     * @param x_pos X coordinate of the object.
     * @param y_pos Y coordinate of the object.
     * @param priority Integer representing priority of the object, when other object might attempt to interact with several objects at a time.
     * @param destroy_after_interaction Flag, informing whther or not this object should be destroyed after one interaction with other object.
     */
    InteractiveObject(const std::string initial_texture_name, const ObjectType object_type, const int x_pos, const int y_pos,
        const int priority = constants::OTHER_OBJECT_PRIORITY, const bool destroy_after_interaction = false);

    InteractiveObject();

    /**
     * @brief Do some action regarding fact that another object is attempting to interact with this object.
     *
     */
    virtual void interact() = 0;

    /// @brief get X position of the object.
    int getXPos() const;

    /// @brief get Y position of the object.
    int getYPos() const;

    /**
     * @brief Get the priority of the object.
     *
     * In another object is attempting to interact with several object at the time,
     * the other object, based on context of interaction, should interact with objects with bigger priority first.
     * The bigger the value of priority is, the more important this object is,
     * and this object has bigger priority with interacting with other objects.
     * @return int Priority of the object.
     */
    int getPriority() const;

    /**
     * @brief Get the Priority object, based on WorldArmy, which is attempting to interact with this object.
     * In few situations, the priority of the object might change based on which world army (on world map) is interacting with this object.
     *
     * @return int Priority of the object, with respect to world army which interacts with this object.
     */
    virtual int getPriority(WorldArmy&) const;

    /**
     * @brief Get the bool flag informing wether or not this object should be destroyed after interaction.
     *
     * Several objects might be immediately removed from the game the moment the other object is interacting with them.
     *
     * @return true if object should be destroyed immediately after interaction, false otherwise.

     */
    bool getFlagDestroyAfterInteraction() const;

    /**
     * @brief Set the flag destroy_after_interaction_ to true, informing the game that this object should be now removed from the game.
     *
     * In few situations, object should be destroyed only after some conditions are met.
     * This method will set the bool variable destroy_after_interaction_ to true.
     *
     */
    void setFlagDestroyAfterInteraction();


    /// @brief Get ObjectType of this object
    ObjectType getInteractiveObjectType() const;

    /**
     * @brief Draw additional elements into tile on GUI.
     *
     * Normally, game tile is drawn into display, the texture of tile and this object are drawn.
     * This method will draw new additional elements on QPixmap generated by this object.
     *
     * For example, several objects, which are controlled by player, should have indicator drawn on them, informing user of owner of this object.
     */
    virtual void drawAdditionalData(IPainter&) const;

};

#endif