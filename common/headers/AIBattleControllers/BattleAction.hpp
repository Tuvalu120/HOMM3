#ifndef BATTLE_ACTION_HPP
#define BATTLE_ACTION_HPP

#include <string>

/**
 * @enum BattleAction
 * @brief This enum represents various heuristics used by AI players.
 *
 */
enum BattleAction{
    ATTACK_CLOSEST_ENEMY,
    ATTACK_FURTHEST_ENEMY,
    ATTACK_ENEMY_WITH_LOWEST_HEALTH,
    ATTACK_ENEMY_WITH_BIGGEST_HEALTH,
    ATTACK_ENEMY_WITH_LOWEST_ATTACK,
    ATTACK_ENEMY_WITH_BIGGEST_ATTACK,
    GO_FORWARD,
    HIDE_STACK,
    GO_TO_FRIENDLY_STACKS,
    SPREAD_FROM_FRIENDLY_STACKS,
    ATTACK_ENEMY_FOR_BIGGEST_ATTACK_LOSS,
    EXECUTE_ENEMY_WITH_BIGGEST_ATTACK,
    ATTACK_ENEMY_WITH_BIGGEST_RANGE,
    ATTACK_ENEMY_WHICH_CAN_KILL_MY_STACK,
    ATTACK_ENEMY_WHICH_CAN_REDUCE_MY_ATTACK_BY_MOST,
    ATTACK_ENEMY_WHICH_IS_NEXT_IN_ORDER,
    PROTECT_STRONGEST_FRIENDLY_STACK,
    DO_NOTHING_BATTLE_ACTION,
    N_BATTLE_ACTIONS
};

/**
 * @brief Get string description of BattleAction
 * @param action BattleAction to get string from.
 */
inline std::string actionToString(const BattleAction action){
    switch(action){
        case ATTACK_CLOSEST_ENEMY: return "ATTACK_CLOSEST_ENEMY";
        case ATTACK_FURTHEST_ENEMY: return "ATTACK_FURTHEST_ENEMY";
        case ATTACK_ENEMY_WITH_LOWEST_HEALTH: return "ATTACK_ENEMY_WITH_LOWEST_HEALTH";
        case ATTACK_ENEMY_WITH_BIGGEST_HEALTH: return "ATTACK_ENEMY_WITH_BIGGEST_HEALTH";
        case ATTACK_ENEMY_WITH_LOWEST_ATTACK: return "ATTACK_ENEMY_WITH_LOWEST_ATTACK";
        case ATTACK_ENEMY_WITH_BIGGEST_ATTACK: return "ATTACK_ENEMY_WITH_BIGGEST_ATTACK";
        case GO_FORWARD: return "GO_FORWARD";
        case HIDE_STACK: return "HIDE_STACK";
        case GO_TO_FRIENDLY_STACKS: return "GO_TO_FRIENDLY_STACKS";
        case SPREAD_FROM_FRIENDLY_STACKS: return "SPREAD_FROM_FRIENDLY_STACKS";
        case ATTACK_ENEMY_FOR_BIGGEST_ATTACK_LOSS: return "ATTACK_ENEMY_FOR_BIGGEST_ATTACK_LOSS";
        case EXECUTE_ENEMY_WITH_BIGGEST_ATTACK: return "EXECUTE_ENEMY_WITH_BIGGEST_ATTACK";
        case ATTACK_ENEMY_WITH_BIGGEST_RANGE: return "ATTACK_ENEMY_WITH_BIGGEST_RANGE";
        case ATTACK_ENEMY_WHICH_CAN_KILL_MY_STACK: return "ATTACK_ENEMY_WHICH_CAN_KILL_MY_STACKS";
        case ATTACK_ENEMY_WHICH_CAN_REDUCE_MY_ATTACK_BY_MOST: return "ATTACK_ENEMY_WHICH_CAN_REDUCE_MY_ATTACK_BY_MOST";
        case ATTACK_ENEMY_WHICH_IS_NEXT_IN_ORDER: return "ATTACK_ENEMY_WHICH_IS_NEXT_IN_ORDER";
        case PROTECT_STRONGEST_FRIENDLY_STACK: return "PROTECT_STRONGEST_FRIENDLY_STACK";
        case DO_NOTHING_BATTLE_ACTION: return "DO_NOTHING_BATTLE_ACTION";
        default: return "UNKNOWN_ACTION";
    }
};

#endif